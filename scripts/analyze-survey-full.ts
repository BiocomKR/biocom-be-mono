// SIB API 호출
async function getGlutenLevel(phone: string): Promise<{ hasGluten45: boolean; glutenLevel: string | null }> {
  const normalizedPhone = phone.replace(/[-\s]/g, '');

  try {
    // 1. 전화번호로 chartId 조회
    const chartRes = await axios.get(
      `https://sib.codns.com:3001/api/challenge/chartIdByMobile?mobile=${normalizedPhone}`,
      { timeout: 5000 }
    );

    const chartList = chartRes.data;
    if (!chartList || chartList.length === 0) {
      return { hasGluten45: false, glutenLevel: null };
    }

    // D0004, D0060 필터링 후 최신 것
    const iggExams = chartList.filter((e: any) => ['D0004', 'D0060'].includes(e.orderCode));
    if (iggExams.length === 0) {
      return { hasGluten45: false, glutenLevel: null };
    }

    const latestExam = iggExams.sort((a: any, b: any) =>
      new Date(b.receiptDate).getTime() - new Date(a.receiptDate).getTime()
    )[0];

    if (latestExam.resultYN !== 'Y') {
      return { hasGluten45: false, glutenLevel: null };
    }

    // 2. IgG Levels 조회
    const levelRes = await axios.get(
      `https://sib.codns.com:3001/api/report/getIggLevels?chartId=${latestExam.chartID}`,
      { timeout: 5000 }
    );

    const levels = levelRes.data;
    if (!levels || levels.length === 0) {
      return { hasGluten45: false, glutenLevel: null };
    }

    const result = levels[0];

    // 글루텐이 level4 또는 level5에 있는지 확인
    const level4Items = (result.level4 || '').split(',').map((s: string) => s.trim().toLowerCase());
    const level5Items = (result.level5 || '').split(',').map((s: string) => s.trim().toLowerCase());

    const inLevel4 = level4Items.some((item: string) => item.includes('글루텐') || item.includes('gluten'));
    const inLevel5 = level5Items.some((item: string) => item.includes('글루텐') || item.includes('gluten'));

    if (inLevel5) return { hasGluten45: true, glutenLevel: '5' };
    if (inLevel4) return { hasGluten45: true, glutenLevel: '4' };

    return { hasGluten45: false, glutenLevel: null };
  } catch (error: any) {
    // 조회 실패 시 조용히 처리
    return { hasGluten45: false, glutenLevel: null };
  }
}

// 동점 시 우선순위 적용하여 최고점 카테고리 찾기
function findDominantCategory(scores: Record<string, number>): string {
  const maxScore = Math.max(...PRIORITY.map(cat => scores[cat] || 0));

  // 우선순위 순서대로 확인
  for (const cat of PRIORITY) {
    if (scores[cat] === maxScore) {
      return cat;
    }
  }

  return 'GUT_HEALTH';
}

// 설문 분석
function analyzeSurvey(answers: string[]): { category: string; scores: Record<string, number> } {
  const scores: Record<string, number> = {
    'SKIN_HEALTH': 0,
    'METABOLISM': 0,
    'GUT_HEALTH': 0,
    'IMMUNE_BALANCE': 0,
    'SLEEP': 0,
  };

  for (let i = 0; i < 25; i++) {
    const answer = answers[i];
    const category = QUESTION_CATEGORIES[i + 1];
    const score = SCORE_MAP[answer] ?? 0;
    scores[category] += score;
  }

  const category = findDominantCategory(scores);
  return { category, scores };
}

